package _21_J_LOOPS;

public class For_While_Do_while {

	public static void main(String[] args) {

		System.out.println("FOR LOOP");
		for(int x=0; x<=5; x++){

			System.out.println(x);

		}
		System.out.println("------------------------");
		System.out.println("WHILE LOOP");

		int x=0;

		while(x<=5){

			System.out.println(x);

			x++;

		}
		System.out.println("------------------------");
		System.out.println("DO WHILE LOOP");
		int Z=0;

		do{

			System.out.println(Z);

			Z++;

		}while(Z<=5);
	}

}
